import logging
import time
import uuid
from typing import Optional

from app.schemas.plan import ResearchResponse
from app.workflows.research_graph import research_graph
from app.workflows.states import ResearchState

logger = logging.getLogger(__name__)


def run_research_workflow(query: str, run_id: Optional[str] = None) -> ResearchResponse:
    """
    Entry point called by the FastAPI /api/research endpoint.

    Executes the compiled LangGraph workflow with the user's research query
    and returns a structured ResearchResponse.

    Args:
        query: The user's research topic or question.
        run_id: Optional workflow correlation ID (autogenerated if not supplied).

    Returns:
        ResearchResponse with the final answer and retrieved sources.

    Raises:
        ValueError: If query is blank.
        RuntimeError: If graph execution fails.
    """
    cleaned_query = query.strip()
    if not cleaned_query:
        raise ValueError("Research query cannot be empty.")

    active_run_id = run_id or uuid.uuid4().hex[:8]
    workflow_start_time = time.perf_counter()
    logger.info("[run: %s] [WORKFLOW START] Initiating LangGraph research pipeline...", active_run_id)

    initial_state: ResearchState = {
        "run_id": active_run_id,
        "user_query": cleaned_query,
        "analysis": None,
        "search_query": None,
        "search_results": [],
        "evaluation": None,
        "retry_count": 0,
        "final_answer": None,
    }

    try:
        final_state = research_graph.invoke(initial_state)
    except Exception as exc:
        total_elapsed = time.perf_counter() - workflow_start_time
        logger.error(
            "[run: %s] [WORKFLOW ERROR] LangGraph execution failed after %.2fs: %s",
            active_run_id,
            total_elapsed,
            exc,
        )
        raise RuntimeError(f"LangGraph execution failed: {exc}") from exc

    total_elapsed = time.perf_counter() - workflow_start_time
    logger.info(
        "[run: %s] [WORKFLOW COMPLETE] Total workflow execution completed in %.2fs (%d sources).",
        active_run_id,
        total_elapsed,
        len(final_state.get("search_results") or []),
    )

    return ResearchResponse(
        query=cleaned_query,
        answer=final_state.get("final_answer") or "No answer was produced by the workflow.",
        sources=final_state.get("search_results") or [],
    )

