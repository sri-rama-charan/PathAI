# ==============================================================================
# File: server/app/schemas.py
# Purpose: Pydantic schemas for request validation, structured LLM outputs, and responses.
#
# What this file does:
# 1. PlanRequest: Validates incoming user inputs from the React frontend.
# 2. DayPlan: Structured day-by-day learning plan unit.
# 3. LearningPlan: Full curriculum containing overview, prerequisites, and days.
# 4. PlanResult: Feasibility assessment and optional LearningPlan (for Gemini structured output).
# 5. PlanResponse: Standard API response wrapper returning the PlanResult.
# ==============================================================================

import datetime
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator, AliasChoices


# ==============================================================================
# 1. Incoming Request Model
# ==============================================================================

class PlanRequest(BaseModel):
    """
    Request schema for creating a learning plan configuration.
    """
    goal: str = Field(
        ...,
        min_length=1,
        description="The primary skill or subject the user wants to learn.",
        examples=["Learn RAG with LangChain"],
    )
    experience: str = Field(
        ...,
        min_length=1,
        description="The user's existing technical knowledge or experience level.",
        examples=["Learned python basics, familiar with linear regression"],
    )
    durationDays: int = Field(
        ...,
        gt=0,
        le=365,
        description="Total duration in days (must be greater than 0).",
        examples=[30],
    )
    hoursPerDay: float = Field(
        ...,
        gt=0.0,
        le=24.0,
        description="Dedicated study hours per day (must be greater than 0).",
        examples=[2.0],
    )
    startDate: datetime.date = Field(
        ...,
        description="Target start date in YYYY-MM-DD format.",
        examples=["2026-09-11"],
    )
    resourcePreferences: List[str] = Field(
        default_factory=list,
        validation_alias=AliasChoices("resourcePreferences", "preferences"),
        description="Optional list of preferred resource types (e.g. videos, courses).",
        examples=[["videos", "documentation", "courses", "projects"]],
    )

    # --------------------------------------------------------------------------
    # Field Validators
    # --------------------------------------------------------------------------
    @field_validator("goal", "experience")
    @classmethod
    def validate_not_blank(cls, value: str) -> str:
        """
        Ensures that string fields are not just blank spaces (e.g. '   ').
        """
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Field cannot be empty or contain only whitespace.")
        return cleaned


# ==============================================================================
# 2. Structured LLM Output Models (Gemini Response Schemas)
# ==============================================================================

class DayPlan(BaseModel):
    """
    Represents a single day's structured learning plan.
    """
    day: int = Field(..., description="Sequential day number (1-indexed).")
    date: datetime.date = Field(..., description="Calendar date corresponding to this day.")
    topic: str = Field(..., description="Main topic or focus for the day.")
    objectives: List[str] = Field(..., description="Key concept milestones to understand.")
    tasks: List[str] = Field(..., description="Actionable hands-on tasks or study exercises.")
    estimatedHours: float = Field(..., description="Estimated hours allocated for this day.")


class LearningPlan(BaseModel):
    """
    Full curriculum generated by the AI when the requested time is feasible.
    """
    title: str = Field(..., description="Descriptive title of the generated curriculum.")
    overview: str = Field(..., description="High-level summary of what the user will master.")
    prerequisites: List[str] = Field(..., description="Key foundational concepts assumed or reviewed.")
    days: List[DayPlan] = Field(..., description="Sequential list of daily plans.")


class PlanResult(BaseModel):
    """
    AI Feasibility assessment and optional LearningPlan.
    
    If the requested time is insufficient for the goal:
      feasible is False, plan is None, and recommendations explain alternatives.
    If the requested time is sufficient:
      feasible is True, and plan contains the full daily curriculum.
    """
    feasible: bool = Field(
        ...,
        description="True if the available time is reasonably sufficient for the goal.",
    )
    feasibilityMessage: str = Field(
        ...,
        description="Explanation of the feasibility judgment.",
    )
    estimatedRequiredHours: float = Field(
        ...,
        description="AI's estimated total hours needed to achieve this goal realistically.",
    )
    availableHours: float = Field(
        ...,
        description="Total available hours provided by user (durationDays * hoursPerDay).",
    )
    recommendations: List[str] = Field(
        default_factory=list,
        description="Actionable suggestions (e.g. adjust scope, change duration).",
    )
    plan: Optional[LearningPlan] = Field(
        default=None,
        description="The detailed curriculum if feasible, otherwise None.",
    )


# ==============================================================================
# 3. API Response Wrapper
# ==============================================================================

class PlanResponse(BaseModel):
    """
    Standard API response wrapper returned by POST /api/plan.
    """
    message: str = Field(
        ...,
        description="Status message confirming request outcome.",
        examples=["Learning plan generated successfully"],
    )
    data: PlanResult = Field(
        ...,
        description="The feasibility analysis and optional learning plan.",
    )


# ==============================================================================
# 4. Web Search Models (Provider-Independent)
# ==============================================================================

class SearchResult(BaseModel):
    """
    Provider-independent representation of a web search result.
    
    Why this is provider-independent:
    Different search engines (Tavily, Google, DuckDuckGo, Bing) return different
    key names (like 'content', 'snippet', 'snippet_text', 'link', etc.).
    By normalizing everything into SearchResult(title, url, description, source),
    our agent code never depends on Tavily's specific API structure.
    """
    title: str = Field(..., description="Title of the web resource.")
    url: str = Field(..., description="Canonical URL of the web resource.")
    description: str = Field(..., description="Brief snippet or summary of the page content.")
    source: str = Field(..., description="Origin domain or source platform (e.g. docs.python.org).")


class SearchResponse(BaseModel):
    """
    Standard API response model for GET /api/search.
    """
    query: str = Field(..., description="The search query that was executed.")
    results: List[SearchResult] = Field(
        default_factory=list,
        description="List of normalized web search results.",
    )

